// Docker-only offline generation from the audited public OpenAPI; no credentials or API requests.
import { readFileSync, writeFileSync } from "node:fs";
const api = JSON.parse(
  readFileSync("docs/contracts/iacp-deployed-20261026-061.json", "utf8"),
);
function type(s) {
  if (s.$ref) return s.$ref.split("/").at(-1);
  if (Object.hasOwn(s, "const")) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(type).join(" | ");
  if (s.type === "array") return `Array<${type(s.items ?? {})}>`;
  if (s.type === "object" || s.properties) {
    const props = Object.entries(s.properties ?? {})
      .map(
        ([k, v]) =>
          `${JSON.stringify(k)}${(s.required ?? []).includes(k) ? "" : "?"}: ${type(v)}`,
      )
      .join("; ");
    return (
      "{ " +
      [props, s.additionalProperties === true ? "[key: string]: unknown" : ""]
        .filter(Boolean)
        .join("; ") +
      " }"
    );
  }
  return (
    {
      string: "string",
      integer: "number",
      number: "number",
      boolean: "boolean",
      null: "null",
    }[s.type] ?? "unknown"
  );
}
const operations = {};
for (const [path, item] of Object.entries(api.paths))
  for (const [method, op] of Object.entries(item))
    if (["get", "post", "delete", "patch", "put"].includes(method))
      operations[op.operationId] = {
        method: method.toUpperCase(),
        path,
        parameters: (op.parameters ?? [])
          .filter((p) => p.in === "path" || p.in === "query")
          .map((p) => ({ name: p.name, in: p.in })),
        request: op.requestBody?.content?.["application/json"]?.schema ?? null,
        response:
          op.responses?.["202"]?.content?.["application/json"]?.schema ??
          op.responses?.["200"]?.content?.["application/json"]?.schema ??
          null,
      };
const source =
  "// Generated by scripts/generate-iacp-client.mjs. Do not edit. No runtime examples/secrets.\n" +
  Object.entries(api.components.schemas)
    .map(([name, s]) => `export type ${name} = ${type(s)};`)
    .join("\n") +
  "\nexport const iacpOperations = " +
  JSON.stringify(operations, null, 2) +
  " as const;\nexport type IacpOperationId = keyof typeof iacpOperations;\n";
writeFileSync("src/lib/types/iacp.generated.ts", source);
console.log(
  `Generated ${Object.keys(operations).length} operations and ${Object.keys(api.components.schemas).length} types offline`,
);
